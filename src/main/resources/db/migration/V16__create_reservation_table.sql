CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE reservation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    court_id BIGINT NOT NULL,
    member_id BIGINT,
    source VARCHAR(20) NOT NULL DEFAULT 'MEMBER',
    date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'CONFIRMED',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_by_user_id BIGINT NOT NULL,
    cancelled_at TIMESTAMPTZ,
    cancelled_by_user_id BIGINT,
    CONSTRAINT fk_reservation_court FOREIGN KEY (court_id) REFERENCES court(id),
    CONSTRAINT fk_reservation_member FOREIGN KEY (member_id) REFERENCES member(id),
    CONSTRAINT fk_reservation_created_by FOREIGN KEY (created_by_user_id) REFERENCES user_account(id),
    CONSTRAINT fk_reservation_cancelled_by FOREIGN KEY (cancelled_by_user_id) REFERENCES user_account(id),
    CONSTRAINT ck_reservation_source CHECK (source IN ('MEMBER', 'RECURRING', 'ACTIVITY')),
    CONSTRAINT ck_reservation_status CHECK (status IN ('CONFIRMED', 'CANCELLED')),
    CONSTRAINT ck_reservation_ends_after_starts CHECK (end_time > start_time),
    CONSTRAINT ck_reservation_member_or_activity CHECK (member_id IS NOT NULL OR source = 'ACTIVITY'),
    CONSTRAINT ck_reservation_cancel_fields_together CHECK ((cancelled_at IS NULL) = (cancelled_by_user_id IS NULL)),
    CONSTRAINT ck_reservation_cancelled_status CHECK ((status = 'CANCELLED') = (cancelled_at IS NOT NULL)),
    CONSTRAINT ex_reservation_no_overlap EXCLUDE USING gist (
        court_id WITH =,
        tsrange(date + start_time, date + end_time) WITH &&
    ) WHERE (status = 'CONFIRMED')
);

CREATE INDEX idx_reservation_court_id_date ON reservation(court_id, date);
CREATE INDEX idx_reservation_member_id ON reservation(member_id);
CREATE INDEX idx_reservation_created_by_user_id ON reservation(created_by_user_id);
CREATE INDEX idx_reservation_cancelled_by_user_id ON reservation(cancelled_by_user_id);
