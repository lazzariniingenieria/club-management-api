CREATE TABLE recurring_slot (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    court_id BIGINT NOT NULL,
    member_id BIGINT,
    description VARCHAR(100),
    day_of_week SMALLINT NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    valid_from DATE NOT NULL,
    valid_until DATE NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_by_user_id BIGINT NOT NULL,
    deactivated_at TIMESTAMPTZ,
    deactivated_by_user_id BIGINT,
    CONSTRAINT fk_recurring_slot_court FOREIGN KEY (court_id) REFERENCES court(id),
    CONSTRAINT fk_recurring_slot_member FOREIGN KEY (member_id) REFERENCES member(id),
    CONSTRAINT fk_recurring_slot_created_by FOREIGN KEY (created_by_user_id) REFERENCES user_account(id),
    CONSTRAINT fk_recurring_slot_deactivated_by FOREIGN KEY (deactivated_by_user_id) REFERENCES user_account(id),
    CONSTRAINT ck_recurring_slot_iso_day_of_week CHECK (day_of_week BETWEEN 1 AND 7),
    CONSTRAINT ck_recurring_slot_ends_after_starts CHECK (end_time > start_time),
    CONSTRAINT ck_recurring_slot_validity_up_to_one_year CHECK (
        valid_until > valid_from AND valid_until <= valid_from + INTERVAL '1 year'
    ),
    CONSTRAINT ck_recurring_slot_member_or_description CHECK ((member_id IS NULL) <> (description IS NULL)),
    CONSTRAINT ck_recurring_slot_deactivation_fields_together CHECK ((deactivated_at IS NULL) = (deactivated_by_user_id IS NULL)),
    CONSTRAINT ck_recurring_slot_active_until_deactivated CHECK (active = (deactivated_at IS NULL))
);

CREATE INDEX idx_recurring_slot_court_id ON recurring_slot(court_id);
CREATE INDEX idx_recurring_slot_member_id ON recurring_slot(member_id);
CREATE INDEX idx_recurring_slot_created_by_user_id ON recurring_slot(created_by_user_id);
CREATE INDEX idx_recurring_slot_deactivated_by_user_id ON recurring_slot(deactivated_by_user_id);

ALTER TABLE reservation ADD COLUMN recurring_slot_id BIGINT;
ALTER TABLE reservation ADD CONSTRAINT fk_reservation_recurring_slot FOREIGN KEY (recurring_slot_id) REFERENCES recurring_slot(id);
ALTER TABLE reservation DROP CONSTRAINT ck_reservation_member_or_activity;
ALTER TABLE reservation ADD CONSTRAINT ck_reservation_member_unless_activity CHECK ((member_id IS NULL) = (source = 'ACTIVITY'));
ALTER TABLE reservation ADD CONSTRAINT ck_reservation_recurring_slot_unless_member
    CHECK ((recurring_slot_id IS NULL) = (source = 'MEMBER'));

CREATE INDEX idx_reservation_recurring_slot_id ON reservation(recurring_slot_id);
