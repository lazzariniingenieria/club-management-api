CREATE TABLE court (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    club_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    type VARCHAR(50),
    opening_time TIME NOT NULL,
    closing_time TIME NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_by_user_id BIGINT,
    updated_by_user_id BIGINT,
    CONSTRAINT fk_court_club FOREIGN KEY (club_id) REFERENCES club(id),
    CONSTRAINT fk_court_created_by FOREIGN KEY (created_by_user_id) REFERENCES user_account(id),
    CONSTRAINT fk_court_updated_by FOREIGN KEY (updated_by_user_id) REFERENCES user_account(id),
    CONSTRAINT ck_court_closing_after_opening CHECK (closing_time > opening_time)
);

CREATE UNIQUE INDEX uk_court_club_name ON court (club_id, LOWER(name));
CREATE INDEX idx_court_created_by_user_id ON court(created_by_user_id);
CREATE INDEX idx_court_updated_by_user_id ON court(updated_by_user_id);
