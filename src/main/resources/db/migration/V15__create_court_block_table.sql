CREATE TABLE court_block (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    court_id BIGINT NOT NULL,
    starts_at TIMESTAMP NOT NULL,
    ends_at TIMESTAMP NOT NULL,
    reason VARCHAR(150),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_by_user_id BIGINT NOT NULL,
    CONSTRAINT fk_court_block_court FOREIGN KEY (court_id) REFERENCES court(id),
    CONSTRAINT fk_court_block_created_by FOREIGN KEY (created_by_user_id) REFERENCES user_account(id),
    CONSTRAINT ck_court_block_ends_after_starts CHECK (ends_at > starts_at)
);

CREATE INDEX idx_court_block_court_id_starts_at ON court_block(court_id, starts_at);
CREATE INDEX idx_court_block_created_by_user_id ON court_block(created_by_user_id);
