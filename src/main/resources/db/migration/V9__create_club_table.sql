CREATE TABLE club (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    address VARCHAR(255),
    courts_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    member_app_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    monthly_fee_amount NUMERIC(10, 2),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_club_monthly_fee_amount_positive CHECK (monthly_fee_amount IS NULL OR monthly_fee_amount > 0)
);

-- Every club_id already stored on a root table gets a club row, so the foreign keys added in V10 cannot fail on
-- existing data. Club 1 is the only one expected; the name is a placeholder to be set per environment.
INSERT INTO club (id, name)
SELECT referenced.club_id, 'Club ' || referenced.club_id
FROM (SELECT club_id FROM member
      UNION
      SELECT club_id FROM user_account
      UNION
      SELECT 1) AS referenced;

-- Ids were inserted explicitly, so the identity sequence is moved past them before the next generated id.
SELECT setval(pg_get_serial_sequence('club', 'id'), (SELECT MAX(id) FROM club));
